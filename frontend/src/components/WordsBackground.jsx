const ROW_COUNT = 20;
const NAVBAR_HEIGHT = 60;

function buildRow(offset) {
  const arr = [];
  for (let i = 0; i < 18; i++) arr.push(WORDS[(offset + i) % WORDS.length]);
  const str = arr.join("  ·  ") + "  ·  ";
  return str + str;
}

export default function WordsBackground() {
  return (
    <div style={{
      position: "fixed",
      top: NAVBAR_HEIGHT,
      left: 0,
      right: 0,
      bottom: 0,
      zIndex: 0,
      overflow: "hidden",
      pointerEvents: "none",
      userSelect: "none",
    }}>
      <style>{`
        @keyframes scrollLeft {
          from { transform: translateX(0); }
          to { transform: translateX(-50%); }
        }
        @keyframes scrollRight {
          from { transform: translateX(-50%); }
          to { transform: translateX(0); }
        }
      `}</style>
      {Array.from({ length: ROW_COUNT }).map((_, i) => {
        const goLeft = i % 2 === 0;
        const speed = 70 + (i % 5) * 15;
        return (
          <div key={i} style={{
            whiteSpace: "nowrap",
            lineHeight: "2.4",
            animation: `${goLeft ? "scrollLeft" : "scrollRight"} ${speed}s linear infinite`,
            willChange: "transform",
          }}>
            <span style={{
              fontFamily: "var(--font-sans)",
              fontSize: "0.75rem",
              fontWeight: 300,
              letterSpacing: "0.04em",
              color: "rgba(26,25,23,0.10)",
            }}>
              {buildRow(i * 11)}
            </span>
          </div>
        );
      })}
    </div>
  );
}
