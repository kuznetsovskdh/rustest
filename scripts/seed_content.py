"""Наполнение каталога тестов и справочника правил демонстрационным контентом.

Работает через публичный API (nginx на localhost:3001), а не напрямую в БД —
так же, как это делал бы админ через интерфейс.

    python3 scripts/seed_content.py --email admin@example.com --password ...

Скрипт идемпотентен по названиям: тест или правило с совпадающим заголовком
не создаётся повторно.
"""

import argparse
import json
import sys
import urllib.error
import urllib.request

BASE = "http://localhost:3001/api"


def call(method, path, token=None, body=None):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(BASE + path, data=data, method=method)
    if data:
        req.add_header("Content-Type", "application/json")
    if token:
        req.add_header("Authorization", "Bearer " + token)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            payload = r.read()
            return json.loads(payload) if payload else {}
    except urllib.error.HTTPError as e:
        print(f"  ! {method} {path} -> {e.code}: {e.read()[:200].decode(errors='replace')}")
        return None


